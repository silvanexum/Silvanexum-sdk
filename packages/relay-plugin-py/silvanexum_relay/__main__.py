"""``python -m silvanexum_relay init <dir>``: write an installable Relay worker folder.

Relay installs a Python worker by running pip on the folder named by the
manifest's ``source.manifest_root``, and checks the SHA-256 of the manifest's
``source.artifact``. A wheel installed from PyPI has neither a project folder nor
a manifest, so this command generates a tiny wrapper project that depends on
``silvanexum-relay`` and re-exports its entrypoint, plus a manifest whose digest
matches the wrapper's ``worker.py``. Then:

    nemo-relay plugins add <dir>/relay-plugin.toml
    nemo-relay plugins enable silvanexum
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path

_WORKER = '''"""Relay entrypoint shim generated by `python -m silvanexum_relay init`."""
from silvanexum_relay.worker import main

__all__ = ["main"]
'''

_PYPROJECT = """[build-system]
requires = ["setuptools>=68"]
build-backend = "setuptools.build_meta"

[project]
name = "silvanexum-relay-worker"
version = "{version}"
requires-python = ">=3.11"
dependencies = ["{requirement}"]

[tool.setuptools]
packages = ["silvanexum_relay_worker"]
"""

_MANIFEST = """# NeMo Relay worker manifest generated by `python -m silvanexum_relay init`.
# Install:  nemo-relay plugins add ./relay-plugin.toml && nemo-relay plugins enable silvanexum
# Re-run the init command after upgrading silvanexum-relay.
manifest_version = 1

[plugin]
id = "silvanexum"
kind = "worker"

[compat]
relay = ">=0.11.0,<1.0"
worker_protocol = "grpc-v1"

[defaults]
enabled = false

[capabilities]
items = ["plugin_worker"]

[source]
manifest_root = "."
artifact = "silvanexum_relay_worker/worker.py"

[integrity]
sha256 = "sha256:{digest}"

[load]
runtime = "python"
entrypoint = "silvanexum_relay_worker.worker:main"
"""


def _installed_version() -> str:
    try:
        return version("silvanexum-relay")
    except PackageNotFoundError:
        return "0.0.0"


def init(target: Path, *, requirement: str | None = None, force: bool = False) -> Path:
    """Write the wrapper project into ``target`` and return the manifest path."""
    pkg_version = _installed_version()
    requirement = requirement or f"silvanexum-relay=={pkg_version}"
    manifest = target / "relay-plugin.toml"
    if manifest.exists() and not force:
        raise FileExistsError(f"{manifest} already exists (pass --force to overwrite)")
    pkg = target / "silvanexum_relay_worker"
    pkg.mkdir(parents=True, exist_ok=True)
    (pkg / "__init__.py").write_text("", encoding="utf-8")
    worker = pkg / "worker.py"
    # Write bytes so the digest Relay computes matches on every OS (no CRLF).
    worker.write_bytes(_WORKER.encode("utf-8"))
    digest = hashlib.sha256(worker.read_bytes()).hexdigest()
    (target / "pyproject.toml").write_text(
        _PYPROJECT.format(version=pkg_version, requirement=requirement), encoding="utf-8"
    )
    manifest.write_text(_MANIFEST.format(digest=digest), encoding="utf-8")
    return manifest


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m silvanexum_relay")
    sub = parser.add_subparsers(dest="command", required=True)
    p_init = sub.add_parser("init", help="Write an installable NeMo Relay worker folder.")
    p_init.add_argument("dir", type=Path, help="Folder to create (e.g. ./silvanexum-relay-plugin)")
    p_init.add_argument(
        "--requirement",
        help="pip requirement for silvanexum-relay (default: the installed version, pinned)",
    )
    p_init.add_argument("--force", action="store_true", help="Overwrite an existing manifest.")
    args = parser.parse_args(argv)

    try:
        manifest = init(args.dir.resolve(), requirement=args.requirement, force=args.force)
    except FileExistsError as ex:
        print(f"error: {ex}", file=sys.stderr)
        return 1
    print(f"Wrote {manifest}")
    print("Next:")
    print(f'  nemo-relay plugins add "{manifest}"')
    print("  nemo-relay plugins enable silvanexum")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
